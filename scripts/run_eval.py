"""Run every experiment and write results/eval.json and results/report.md.

    python -m scripts.run_eval            # mock security gateway (+ Sieve if available)
    python -m scripts.run_eval --quick    # fewer simulated users
"""

import argparse
import json
import time
from pathlib import Path

from drip.sim import experiments as ex

OUT = Path(__file__).resolve().parent.parent / "results"


def pct(x):
    return f"{100 * x:.1f}%"


def f1(x):
    return f"{x:.1f}"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def report(res: dict) -> str:
    md = ["# Evaluation results (generated)", "",
          "Generated by `python -m scripts.run_eval`. **All user-facing numbers are SIMULATION output** "
          "(virtual time, synthetic users, assumptions in `config/sim.json`), not measurements of real people.", ""]

    md += ["## 1. Named security cases: security result and ad result, reported separately", ""]
    rows = []
    for r in res["named_cases"]:
        s, a = r["security"], r["ad"]
        rows.append([r["case"], s["action"].upper(), s["reason"][:38], s["category"], s["sensitivity"],
                     ",".join(s["pii"]) or "-", "yes" if r["llm_called"] else "no",
                     ", ".join(a["ads"]) or "-", f1(a["visible_s"]), a["closed_by"], a["post_decision_signal_category"] or "∅"])
    md += [table(["case", "security", "reason", "category", "sensitivity", "PII", "LLM called",
                  "ads shown", "ad s", "slot closed by", "category sent to ad engine"], rows), ""]

    md += ["## 2. Security detection (synthetic corpus)", ""]
    rows = []
    for mode, s in res["security"].items():
        rows.append([mode, s["n_attacks"], s["n_benign"], pct(s["detection_rate"]), pct(s["block_rate"]),
                     pct(s["false_negative_rate"]), pct(s["false_positive_rate"]), pct(s["fpr_english_benign"]),
                     pct(s["fpr_turkish_benign"]), pct(s["fpr_lookalikes"]), f"{s['latency_ms_mean']:.1f}",
                     f"{s['latency_ms_p95']:.1f}"])
    md += [table(["mode", "attacks", "benign", "detected", "blocked", "FNR", "FPR", "FPR EN docs", "FPR TR docs",
                  "FPR look-alikes", "ms mean", "ms p95"], rows), ""]
    for mode, s in res["security"].items():
        fams = ", ".join(f"{k.split(':')[1]} {pct(v['flagged'])}" for k, v in s["by"].items() if k.startswith("family"))
        car = ", ".join(f"{k.split(':')[1]} {pct(v['flagged'])}" for k, v in s["by"].items() if k.startswith("carrier"))
        md += [f"- **{mode}** by family: {fams}; by carrier: {car}",
               f"  - missed: {', '.join(sorted({m.rsplit('_', 1)[0] for m in s['missed']})) or 'none'}",
               f"  - false positives: {', '.join(f'{n} ({a})' for n, a, _ in s['false_positives']) or 'none'}"]
    md.append("")

    inv = res["invariance"]
    md += ["## 3. Output invariance (ads on vs off)", "",
           f"{inv['identical']} of {inv['runs']} runs (15 documents × 3 strategies × 3 ad-failure modes) produced the "
           "same security decision, the same LLM request fingerprint and the same summary as the run with the ad "
           "engine switched off.", ""]

    ab = res["ab"]
    md += ["## 4. A/B simulation", "",
           f"{ab['n_users']} simulated users per arm (same users in both arms), strategy `{ab['strategy']}`, seed {ab['seed']}.", ""]
    keys = [("completion_rate", "completion (final screen reached)", pct), ("answered_rate", "answered", pct),
            ("abandonment_rate", "abandonment", pct), ("mean_perceived_s", "mean perceived wait (s)", f1),
            ("p90_perceived_s", "p90 perceived wait (s)", f1), ("satisfaction", "satisfaction (1-5)", lambda x: f"{x:.2f}"),
            ("mean_annoyance", "annoyance", lambda x: f"{x:.3f}"), ("ad_eligible_sessions", "ad-eligible sessions", str),
            ("ad_impressions", "billable impressions", str), ("contextual_share", "contextual share of impressions", pct), ("mean_ad_display_s", "mean ad display (s)", f1),
            ("ad_visibility_share", "share of wait covered by ad", pct), ("flash_rate", "flash rate (<1.5 s)", pct),
            ("ctr", "CTR (assumed)", pct), ("ads_per_session", "ads per session", lambda x: f"{x:.2f}"),
            ("revenue_per_1000_jobs_usd", "revenue / 1000 jobs ($)", lambda x: f"{x:.2f}")]
    cols = {"control": ab["control"], "treatment": ab["treatment"], **ab["variants"]}
    md += [table(["metric", *cols], [[label, *(fn(c[k]) for c in cols.values())] for k, label, fn in keys]), ""]

    md += ["### Sensitivity to the key assumption (how an ad-covered second feels)", ""]
    rows = []
    for f, arms in ab["sweep"].items():
        c, t = arms["control"], arms["treatment"]
        rows.append([f, f1(c["mean_perceived_s"]), f1(t["mean_perceived_s"]), pct(c["abandonment_rate"]),
                     pct(t["abandonment_rate"]), f"{c['satisfaction']:.2f}", f"{t['satisfaction']:.2f}"])
    md += [table(["ad_occupied_factor", "perceived ctrl", "perceived treat", "abandon ctrl", "abandon treat",
                  "satisfaction ctrl", "satisfaction treat"], rows), ""]

    md += ["### Ads on documents that turned out to be sensitive", ""]
    rows = [[k, v["sensitive_jobs"], pct(v["share_with_ad"]), f1(v["mean_ad_seconds"]), v["contextual_ads"]]
            for k, v in ab["sensitive_exposure"].items()]
    md += [table(["policy", "sensitive jobs", "with any ad", "mean ad s", "contextual ads"], rows), ""]

    md += ["## 5. Strategy comparison (benign travel document, single-job sessions)", ""]
    rows = []
    for cell, d in res["grid"].items():
        base = d["no_ads"]
        for strat in ("immediate", "delayed", "adaptive"):
            s = d[strat]
            rows.append([cell, strat, pct(s["jobs_with_ad"] / s["jobs"]), f1(s["mean_ad_display_s"]), pct(s["flash_rate"]),
                         f"{s['mean_perceived_s'] - base['mean_perceived_s']:+.2f}",
                         f"{100 * (s['abandonment_rate'] - base['abandonment_rate']):+.1f}pp",
                         f"{s['satisfaction'] - base['satisfaction']:+.2f}", f"{s['revenue_per_1000_jobs_usd']:.2f}"])
    md += [table(["security+LLM s", "strategy", "ad shown", "display s", "flash", "Δ perceived s", "Δ abandon",
                  "Δ satisfaction", "$ / 1000 jobs"], rows), ""]

    eco = res["economics"]
    md += ["## 6. Economics (per 1000 jobs, treatment arm)", "",
           f"UX cost uses ad_occupied_factor = {eco['perception_factor']} (neutral: ads neither shorten nor lengthen "
           "the felt wait), so the model does not book the hoped-for 'occupied time' effect as income.", "",
           f"- billable impressions: {eco['impressions_per_1000_jobs']:.0f}",
           f"- answers lost to ads (negative = gained): {eco['lost_answers_per_1000_jobs']:.1f}",
           f"- ad infrastructure cost: ${eco['infra_cost_per_1000_jobs']:.4f}",
           f"- UX cost (lost answers × assumed value): ${eco['ux_cost_per_1000_jobs']:.3f}",
           f"- break-even eCPM (revenue = infra + UX cost): {'$%.2f' % eco['breakeven_ecpm_usd'] if eco['breakeven_ecpm_usd'] is not None else 'n/a'}",
           "- break-even eCPM if a lost answer is worth: " + ", ".join(
               f"${v} → ${b:.2f}" for v, b in eco["breakeven_by_value_per_lost_answer"].items() if b is not None),
           f"- formula check: eligible sessions × impressions/eligible session × eCPM/1000 = "
           f"${eco['formula_check']['revenue_formula_usd']:.3f} vs simulated ${eco['formula_check']['revenue_simulated_usd']:.3f}", ""]
    llm_keys = [k for k in eco["rows"][0] if k.startswith("covers_")]
    rows = [[f"${r['ecpm_usd']:g}", f"${r['revenue_per_1000_jobs']:.2f}", f"${r['net']:.2f}",
             *(pct(r[k]) for k in llm_keys)] for r in eco["rows"]]
    md += [table(["eCPM", "revenue", "net of costs", *(k.replace("covers_", "covers ") + " cost" for k in llm_keys)], rows), ""]
    sw = res.get("size_workload")
    if sw:
        p = sw["predictor"]
        md += ["## 7. Size-driven chat workload (the wait follows the request)", "",
               f"{sw['n_users']} simulated users, {sw['n_requests']} chat requests. Answer length → wait: "
               "0.3 s security + 0.8 s first token + tokens / 50 per s, answer held back by the output guard.", "",
               "### Wait distribution and predictor accuracy", "",
               "- share of requests by true wait: " + ", ".join(f"{k} {pct(v)}" for k, v in p["wait_share"].items()),
               f"- with streaming (no output guard): {pct(p['streaming_wait_share_below_4s'])} of requests wait < 4 s",
               f"- predictor: median abs. error {pct(p['median_abs_pct_error'])}, within ±50% {pct(p['within_50pct'])}, "
               f"show/no-show decision correct {pct(p['show_decision_accuracy'])}, bucket (<4 / 4–20 / ≥20 s) correct "
               f"{pct(p['bucket_accuracy'])}, short requests predicted long {pct(p['short_requests_predicted_long'])}", ""]
        md += [table(["type", "requests", "mean true wait s", "mean predicted wait s"],
                     [[k, v["n"], f1(v["mean_true_wait_s"]), f1(v["mean_predicted_wait_s"])] for k, v in p["by_type"].items()]), ""]
        md += ["### Arms", ""]
        rows = [[name, pct(a["abandonment_rate"]), f"{a['satisfaction']:.2f}", f1(a["mean_perceived_s"]),
                 pct(a["jobs_with_ad"] / a["jobs"]), f"{a['sponsors_per_shown_request']:.2f}", pct(a["flash_rate"]),
                 f"{a['impressions_per_1000_jobs']:.0f}", f"{a['revenue_per_1000_jobs_usd']:.2f}"]
                for name, a in sw["arms"].items()]
        md += [table(["arm", "abandon", "satisfaction", "perceived s", "requests with ad", "sponsors / shown request",
                      "flash", "impressions / 1000", "$ / 1000"], rows), ""]
        md += ["### By true wait (size predictor + rotation vs control, same users)", ""]
        rows = [[k, v["n"], pct(v["ad_shown"]), f"{v['sponsors_per_request']:.2f}", f"{v['d_abandon_pp']:+.1f}pp",
                 f"{v['d_satisfaction']:+.2f}", f"{v['revenue_per_1000']:.2f}"] for k, v in sw["buckets"].items()]
        md += [table(["true wait", "requests", "with ad", "sponsors / request", "Δ abandon", "Δ satisfaction", "$ / 1000"], rows), ""]
        md += ["### Sensitivity to f (size predictor + rotation)", ""]
        rows = [[f, pct(v["control"]["abandonment_rate"]), pct(v["treatment"]["abandonment_rate"]),
                 f"{v['control']['satisfaction']:.2f}", f"{v['treatment']['satisfaction']:.2f}"] for f, v in sw["sweep"].items()]
        md += [table(["f", "abandon ctrl", "abandon treat", "satisfaction ctrl", "satisfaction treat"], rows), ""]
    return "\n".join(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    n_ab, n_grid, n_size = (500, 60, 500) if args.quick else (4000, 300, 4000)
    t0 = time.time()
    res = {"named_cases": ex.named_cases("mock"), "security": {"mock": ex.security_eval("mock")}}
    try:
        res["security"]["sieve"] = ex.security_eval("sieve")
        res["named_cases_sieve"] = ex.named_cases("sieve")
    except ImportError as e:
        print("Sieve not available, skipping:", e)
    res["invariance"] = ex.invariance()
    res["ab"] = ex.ab_test(n_ab)
    res["grid"] = ex.strategy_grid(n_grid)
    res["economics"] = ex.economics(res["ab"])
    res["economics_optimistic"] = ex.economics(res["ab"], "0.9")
    res["size_workload"] = ex.size_workload(n_size)
    res["runtime_s"] = round(time.time() - t0, 1)
    OUT.mkdir(exist_ok=True)
    (OUT / "eval.json").write_text(json.dumps(res, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
    (OUT / "report.md").write_text(report(res), encoding="utf-8")
    print(f"done in {res['runtime_s']} s -> results/report.md, results/eval.json")


if __name__ == "__main__":
    main()
